import type { Column, Field, Option, Resource, System } from "./types";

const options = (items: Record<string, string>): Option[] =>
  Object.entries(items).map(([value, label]) => ({ value, label }));
const f = (key: string, label: string, extra: Partial<Field> = {}): Field => ({
  key,
  label,
  ...extra,
});
const money = (key: string, label: string, required = true, min = 0): Field =>
  f(key, label, { type: "number", min, step: 1, required, hint: "مبلغ به تومان" });
const d = (key: string, label: string, required = true): Field =>
  f(key, label, { type: "date", required });
const select = (
  key: string,
  label: string,
  values: Record<string, string>,
  required = true,
): Field => f(key, label, { type: "select", options: options(values), required });
const ref = (
  key: string,
  label: string,
  reference: string,
  display: string,
  required = true,
): Field => f(key, label, { type: "select", reference, display, required });
const c = (key: string, label: string, format?: Column["format"]): Column => ({
  key,
  label,
  format,
});
